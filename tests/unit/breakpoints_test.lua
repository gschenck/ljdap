local T = dofile("tests/unit/t.lua")
local breakpoints = require("ljdap.breakpoints")
local paths = require("ljdap.paths")
local eq, check, case = T.eq, T.check, T.case

local cwd = paths.getcwd()
local m = paths.mapper(cwd)
local file = paths.absolute("tests/fixtures/steps.lua", cwd)

case("setzen, verschieben, ersetzen", function()
  local st = breakpoints.new()
  local key, abs = m:from_client(file)
  local res = st:set(key, abs, { { line = 13 }, { line = 17 }, { line = 18 }, { line = 500 } })
  eq(res[1].verified, true)
  eq(res[1].line, 13)
  eq(res[2].line, 19, "Kommentar 17 -> 19")
  eq(res[3].line, 19, "Leerzeile 18 -> 19")
  eq(res[2].id, res[3].id, "gleiche Zielzeile = ein Haltepunkt")
  eq(res[4].verified, false)
  check(res[4].message:find("keine Codezeile"), res[4].message)
  eq(st.count, 2)
  eq(st.lines[13], 1)
  eq(st.lines[19], 1)
  local src = m:from_source("@tests/fixtures/steps.lua")
  check(st:lookup(src, 13), "Treffer 13")
  eq(st:lookup(src, 14), nil)
  eq(st:lookup(nil, 13), nil)
  -- erneut setzen ersetzt
  st:set(key, abs, { { line = 8 } })
  eq(st.count, 1)
  eq(st:lookup(src, 13), nil)
  check(st:lookup(src, 8), "neuer Haltepunkt")
  st:set(key, abs, {})
  eq(st.count, 0)
  eq(next(st.by_key), nil)
end)

case("nicht lesbare Datei", function()
  local st = breakpoints.new()
  local key, abs = m:from_client(paths.absolute("tests/fixtures/fehlt.lua", cwd))
  local res = st:set(key, abs, { { line = 7 } })
  eq(res[1].verified, false)
  eq(res[1].line, 7)
  check(res[1].message:find("nicht lesbar"), res[1].message)
  eq(st.count, 1, "bleibt aktiv")
  check(st:lookup(m:from_source("@tests/fixtures/fehlt.lua"), 7), "Lookup trotzdem")
end)

case("mehrere Dateien, gleiche Zeile", function()
  local st = breakpoints.new()
  local k1, a1 = m:from_client(file)
  local k2, a2 = m:from_client(paths.absolute("tests/fixtures/count.lua", cwd))
  st:set(k1, a1, { { line = 13 } })
  st:set(k2, a2, { { line = 13 } })
  eq(st.lines[13], 2)
  st:clear()
  eq(st.count, 0)
  eq(st.lines[13], nil)
end)

T.finish()
